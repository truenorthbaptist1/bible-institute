"""Puts the church-library book covers on the site.

    python3 tools/library/build_covers.py <work dir> <fonts dir>

<work dir> holds what the cover search produced (tools/library/README.md):
  results.json   one entry per book on the list: {t, a, s, status, cover, ...}
                 status "good"/"check" = a real cover was found ("cover" is the
                 Open Library cover id), "none" = no picture found
  found/<i>.jpg  the real cover picture for book number i
For books without a real cover, a matching stand-in is drawn (make_covers.py).

Writes:
  docs/library/covers/<key>.jpg   small copy the site shows (300 px wide at most)
  docs/js/library-covers.js       which books have a cover (LIBRARY_COVERS)
  supabase/schema.sql             the "library covers" block: attaches each
                                  cover to its book in library_books
  <work dir>/drive/<Title - Author>.jpg   full-size copies for the Drive folder
  <work dir>/covers.csv            the list, for checking by hand

<key> = 8-hex checksum of "title|author" (lower case, spaces collapsed), the
same as libCoverKey() in docs/js/app.js.
"""
import csv
import json
import os
import re
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_covers  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def cover_key(t, a):
    s = re.sub(r"\s+", " ", (t.strip() + "|" + a.strip()).lower())
    h = 0
    for ch in s:
        h = (h * 31 + ord(ch)) & 0xFFFFFFFF
    return f"{h:08x}"


def safe_name(t, a):
    n = f"{t} - {a}" if a else t
    n = re.sub(r'[\\/:*?"<>|]+', " ", n)
    n = re.sub(r"\s+", " ", n).strip().rstrip(".")
    return n[:150]


def site_copy(src, dst):
    im = Image.open(src).convert("RGB")
    im.thumbnail((300, 450), Image.LANCZOS)
    im.save(dst, "JPEG", quality=80, optimize=True, progressive=True)


def main():
    work, fonts = sys.argv[1:3]
    results = json.load(open(os.path.join(work, "results.json")))
    out_site = os.path.join(ROOT, "docs", "library", "covers")
    out_drive = os.path.join(work, "drive")
    made_dir = os.path.join(work, "made")
    for d in (out_site, out_drive, made_dir):
        os.makedirs(d, exist_ok=True)
    for f in os.listdir(out_site):
        os.remove(os.path.join(out_site, f))
    logo = Image.open(make_covers.LOGO).convert("RGBA")

    keys, rows, names = {}, [], set()
    for r in results:
        t, a = r["t"].strip(), (r.get("a") or "").strip()
        k = cover_key(t, a)
        if k in keys:
            if keys[k] != (t.lower(), a.lower()):
                raise SystemExit(f"Two books share cover key {k}: {keys[k]} / {t}")
            continue  # same book on two shelves: one cover
        keys[k] = (t.lower(), a.lower())
        found = os.path.join(work, "found", f"{r['i']}.jpg")
        if r.get("status") in ("good", "check") and os.path.exists(found):
            kind, src = "found", found
        else:
            kind, src = "made", os.path.join(made_dir, f"{k}.jpg")
            make_covers.make({"t": t, "a": a, "s": r.get("s", "")}, fonts, src, logo)
        site_copy(src, os.path.join(out_site, f"{k}.jpg"))
        name = safe_name(t, a)
        while name.lower() in names:
            name += " (2)"
        names.add(name.lower())
        drive_name = f"{name}{' (stand-in)' if kind == 'made' else ''}.jpg"
        Image.open(src).convert("RGB").save(os.path.join(out_drive, drive_name), "JPEG", quality=90)
        rows.append({"key": k, "title": t, "author": a, "shelf": r.get("s", ""), "kind": kind,
                     "match": r.get("status"), "found_as": r.get("olTitle", ""), "found_author": r.get("olAuthors", ""),
                     "open_library": ("https://openlibrary.org" + r["olKey"]) if r.get("olKey") and kind == "found" else "",
                     "drive_file": drive_name})

    # Which books have a cover, for the shelves.
    ks = sorted(r["key"] for r in rows)
    js = ("// Generated by tools/library/build_covers.py — the church-library books that\n"
          "// have a cover picture at library/covers/<key>.jpg (see libCoverKey in app.js).\n"
          "const LIBRARY_COVERS = new Set([\n"
          + "\n".join('  ' + ", ".join(f'"{k}"' for k in ks[i:i + 10]) + "," for i in range(0, len(ks), 10))
          + "\n]);\n")
    open(os.path.join(ROOT, "docs", "js", "library-covers.js"), "w").write(js)

    # Attach each cover to its book in the database. A cover set by hand later
    # is never replaced; a stand-in is replaced when a real cover turns up.
    q = lambda x: "'" + x.replace("'", "''") + "'"
    vals = ",\n".join(f"  ({q(r['title'])}, {q(r['author'])}, 'library/covers/{r['key']}.jpg', '{r['kind']}')" for r in rows)
    block = f"""-- BEGIN library covers (generated by tools/library/build_covers.py — {len(rows)} books)
update public.library_books b set cover = v.cover, cover_kind = v.kind
  from (values
{vals}
  ) as v(title, author, cover, kind)
 where lower(b.title) = lower(v.title) and lower(b.author) = lower(v.author)
   and (b.cover is null or (b.cover_kind = 'made' and v.kind = 'found'));
-- END library covers"""
    p = os.path.join(ROOT, "supabase", "schema.sql")
    schema = open(p).read()
    rx = re.compile(r"-- BEGIN library covers[\s\S]*?-- END library covers")
    schema = rx.sub(lambda m: block, schema) if rx.search(schema) else schema.rstrip() + "\n\n" + block + "\n"
    open(p, "w").write(schema)

    with open(os.path.join(work, "covers.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    n_found = sum(r["kind"] == "found" for r in rows)
    print(f"{len(rows)} books: {n_found} real covers, {len(rows) - n_found} stand-ins")


if __name__ == "__main__":
    main()
