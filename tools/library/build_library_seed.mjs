// Writes the church library's book list (docs/js/library-data.js →
// physicalLibrary) into supabase/schema.sql as the starting list for library
// checkout. Same title + author + shelf = one book with several copies.
// Only fills an EMPTY library_books table, so re-running schema.sql never
// touches books the librarian has edited or added.
//
//   node tools/library/build_library_seed.mjs
import fs from "fs";
const src = fs.readFileSync(new URL("../../docs/js/library-data.js", import.meta.url), "utf8");
const physicalLibrary = new Function(src + "; return physicalLibrary;")();
const groups = new Map();
for (const [t, a, s] of physicalLibrary) {
  const k = `${t.trim().toLowerCase()}|${(a || "").trim().toLowerCase()}|${s}`;
  if (groups.has(k)) groups.get(k).n++;
  else groups.set(k, { t: t.trim(), a: (a || "").trim(), s: (s || "").trim(), n: 1 });
}
const q = (x) => "'" + x.replace(/'/g, "''") + "'";
const rows = [...groups.values()].map((g) => `  (${q(g.t)}, ${q(g.a)}, ${q(g.s)}, ${g.n})`);
const block = `-- BEGIN library seed (generated by tools/library/build_library_seed.mjs — ${rows.length} books, ${physicalLibrary.length} copies)
insert into public.library_books (title, author, subject, copies)
select v.* from (values
${rows.join(",\n")}
) as v(title, author, subject, copies)
where not exists (select 1 from public.library_books);
-- END library seed`;
const p = new URL("../../supabase/schema.sql", import.meta.url);
let schema = fs.readFileSync(p, "utf8");
const re = /-- BEGIN library seed[\s\S]*?-- END library seed/;
schema = re.test(schema) ? schema.replace(re, block) : schema.trimEnd() + "\n\n" + block + "\n";
fs.writeFileSync(p, schema);
console.log(`${rows.length} books (${physicalLibrary.length} copies) written to schema.sql`);
